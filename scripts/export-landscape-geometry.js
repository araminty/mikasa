#!/usr/bin/env node
/**
 * Bake mapping_landscape.html geometry to scripts/mapping_landscape_data.js
 * so the interactive map can load fixed vertices (no runtime RNG).
 *
 * Requires: npm install three
 * Usage: node scripts/export-landscape-geometry.js
 */
'use strict';

const fs = require('fs');
const path = require('path');

let THREE;
try {
  THREE = require('three');
} catch (err) {
  console.error('Missing dependency: run `npm install three` (dev) first.');
  process.exit(1);
}

const buildLandscapeMapData = require('./mapping_landscape_geom.js').buildLandscapeMapData;
const outPath = path.join(__dirname, 'mapping_landscape_data.js');

function formatFloatArray(values, indent, lineWidth) {
  const lines = [];
  let line = indent;
  for (let i = 0; i < values.length; i++) {
    const token = Number(values[i].toFixed(6)).toString();
    const chunk = (line === indent ? '' : ', ') + token;
    if (line.length + chunk.length > lineWidth && line !== indent) {
      lines.push(line + ',');
      line = indent + token;
    } else {
      line += chunk;
    }
  }
  if (line.length > indent.length) lines.push(line);
  return lines.join('\n');
}

function writeDataFile(data) {
  const parts = [];
  parts.push('// Auto-generated by scripts/export-landscape-geometry.js — do not edit by hand.');
  parts.push('// Re-run: node scripts/export-landscape-geometry.js');
  parts.push('const MIKASA_LANDSCAPE_MAP_DATA = {');
  parts.push('  version: ' + data.version + ',');
  parts.push('  seed: ' + data.seed + ',');
  parts.push('  landscape: {');
  parts.push('    positions: [');
  parts.push(formatFloatArray(data.landscape.positions, '      ', 92));
  parts.push('    ]');
  parts.push('  },');
  parts.push('  districts: [');

  for (let d = 0; d < data.districts.length; d++) {
    const district = data.districts[d];
    parts.push('    {');
    parts.push('      name: ' + JSON.stringify(district.name) + ',');
    parts.push('      index: ' + district.index + ',');
    parts.push('      position: [' + district.position.map(function (n) { return Number(n.toFixed(6)); }).join(', ') + '],');
    parts.push('      positions: [');
    parts.push(formatFloatArray(district.positions, '        ', 92));
    parts.push('      ]');
    parts.push('    }' + (d < data.districts.length - 1 ? ',' : ''));
  }

  parts.push('  ],');
  parts.push('  districtCenters: [');
  for (let i = 0; i < data.districtCenters.length; i++) {
    const c = data.districtCenters[i];
    parts.push('    [' + c.map(function (n) { return Number(n.toFixed(6)); }).join(', ') + ']' +
      (i < data.districtCenters.length - 1 ? ',' : ''));
  }
  parts.push('  ],');
  parts.push('  straightTubes: [');
  for (let i = 0; i < data.straightTubes.length; i++) {
    parts.push('    { positions: [');
    parts.push(formatFloatArray(data.straightTubes[i].positions, '        ', 92));
    parts.push('      ]' + (i < data.straightTubes.length - 1 ? ' },' : ' }'));
  }
  parts.push('  ],');
  parts.push('  kinkedTube: { positions: [');
  parts.push(formatFloatArray(data.kinkedTube.positions, '      ', 92));
  parts.push('    ]');
  parts.push('  }');
  parts.push('};');

  fs.writeFileSync(outPath, parts.join('\n') + '\n', 'utf8');
}

console.log('Building landscape map geometry…');
const data = buildLandscapeMapData();
console.log(
  '  landscape line verts:', data.landscape.positions.length / 3,
  '| districts:', data.districts.length,
  '| straight tubes:', data.straightTubes.length
);
writeDataFile(data);
const outHtmlPath = path.join(__dirname, '..', 'out', 'html', 'mapping_landscape_data.js');
fs.writeFileSync(outHtmlPath, fs.readFileSync(outPath, 'utf8'), 'utf8');
console.log('Wrote', outHtmlPath);
